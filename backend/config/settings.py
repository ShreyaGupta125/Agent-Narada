# The secret key signs login sessions and CSRF tokens; anyone who knows it
# could forge them. It is therefore NOT written in this file: it comes
# from the NARADA_SECRET_KEY environment variable if set, otherwise from
# backend/.secret_key, which is created with a new random key on the
# first run. Never share that file.
SECRET_KEY_FILE = BASE_DIR / ".secret_key"


def load_secret_key():
    if os.environ.get("NARADA_SECRET_KEY"):
        return os.environ["NARADA_SECRET_KEY"]
    if not SECRET_KEY_FILE.exists():
        SECRET_KEY_FILE.write_text(secrets.token_urlsafe(50), encoding="utf-8")
    return SECRET_KEY_FILE.read_text(encoding="utf-8").strip()


SECRET_KEY = load_secret_key()

