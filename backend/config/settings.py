# ---------- The language model ----------
# Qwen2.5-1.5B-Instruct runs in a separate program, llama.cpp's
# llama-server.exe, on this computer only. Django sends it the question
# and the permitted passages, and receives the written answer
# (see chat/llm.py).

# Where llama-server listens. 127.0.0.1 means "this computer only".
LLM_SERVER_URL = "http://127.0.0.1:8080"

# A secret shared by Django and llama-server, so no other program or web
# page can use the model. It is read from an environment variable and
# never written in this file. Empty means the server has no key.
