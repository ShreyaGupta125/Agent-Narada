# How long to wait for an answer before giving up, in seconds.
LLM_TIMEOUT_SECONDS = 60

# Randomness of the answer, from 0 to 2. 0 means no randomness: the
# model stays close to the passages instead of being "creative", and the
# same question with the same documents always gets the same answer.
LLM_TEMPERATURE = 0.0

# The longest reply the model may write, in tokens (about 450 words).
# The reply holds the quoted evidence as well as the answer.
LLM_MAX_ANSWER_TOKENS = 600


